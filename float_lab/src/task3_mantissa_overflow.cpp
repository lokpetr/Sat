// ---------------------------------------------------------------------------
// Пункт 3. Переполнение мантиссы: те же таблицы, что и в пункте 0, но с
// ЧЕТВЁРТЫМ столбцом -- представлением результата std::pow в памяти.
// Видно, как в какой-то момент мантисса "упирается" и последние биты
// начинают просто округляться до нуля.
// ---------------------------------------------------------------------------
#include <iostream>

#include "pow_table.h"

int main() {
    std::cout << "=== 3. Переполнение мантиссы: степень | my_pow | std::pow | биты ===\n";

    // Флаг show_bits = true добавляет ровно тот столбец, которого не хватало
    // в пункте 0. Больше ничего менять не надо -- весь код уже переиспользован.
    print_pow_table<float>(3, 100, /*show_bits = */ true);
    print_pow_table<double>(3, 100, /*show_bits = */ true);

    // Что именно происходит в момент потери точности (float, 3^15 -> 3^16).
    std::cout << "\n--- детальная разборка "
                 "границы точности ---";
    for (u64 n = 13; n <= 18; ++n) explain_row<float>(3, n);
    for (u64 n = 33; n <= 35; ++n) explain_row<double>(3, n);
    for (u64 n = 53; n <= 55; ++n) explain_row<double>(3, n);

    std::cout << "\n--- а тут уже кончается не мантисса, а ДИАПАЗОН (float, 3^80/3^81) ---\n";
    for (u64 n = 79; n <= 82; ++n) explain_row<float>(3, n);

    std::cout << "\nвывод: у float 24 значащих бита, поэтому 3^n начинает терять"
                 " младшие единицы\nкак только 3^n > 2^24 (n = 16), а double -- как только 3^n > 2^53"
                 " (n = 34).\nПереполнение мантиссы незаметно глазу: cout с fixed/precision(2)"
                 " печатает то же самое.\n";
    return 0;
}
